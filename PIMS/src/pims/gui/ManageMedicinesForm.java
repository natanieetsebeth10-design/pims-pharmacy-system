    private void loadMedicinesTable() {
        String[] columns = {"ID", "Name", "Company", "Type", "Price", "Qty"};
        tableModel = new javax.swing.table.DefaultTableModel(columns, 0);
        tblMedicines.setModel(tableModel);

        try {
            MedicineDAO dao = new MedicineDAO();
            java.util.List<Medicine> medicines = dao.getAllMedicines();

            for (Medicine m : medicines) {
                tableModel.addRow(new Object[]{
                    m.getMedicineId(),
                    m.getName(),
                    m.getCompany(),
                    m.getMedicineType(),
                    m.getPrice(),
                    m.getQuantityInStock()
                });
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading medicines: " + e.getMessage());
            e.printStackTrace();
        }
    }

