    private void tblMedicinesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMedicinesMouseClicked
        int row = tblMedicines.getSelectedRow();
        if (row == -1) {
            return;
        }

        txtName.setText(tableModel.getValueAt(row, 1).toString());
        txtCompany.setText(tableModel.getValueAt(row, 2).toString());
        txtType.setText(tableModel.getValueAt(row, 3).toString());
        txtPrice.setText(tableModel.getValueAt(row, 4).toString());
        txtQuantity.setText(tableModel.getValueAt(row, 5).toString());

        int medicineId = (int) tableModel.getValueAt(row, 0);
        try {
            MedicineDAO dao = new MedicineDAO();
            java.util.List<Medicine> all = dao.getAllMedicines();
            for (Medicine m : all) {
                if (m.getMedicineId() == medicineId) {
                    txtReorderLevel.setText(String.valueOf(m.getReorderLevel()));
                    txtExpiryDate.setText(m.getExpiryDate().toString());
                    txtSupplierId.setText(m.getSupplierId() != null ? m.getSupplierId().toString() : "");
                    break;
                }
            }
        } catch (java.sql.SQLException e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_tblMedicinesMouseClicked

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
            String name = txtName.getText().trim();
            String company = txtCompany.getText().trim();
            String type = txtType.getText().trim();

            if (name.isEmpty() || txtPrice.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Name and Price are required.");
                return;
            }

            java.math.BigDecimal price = new java.math.BigDecimal(txtPrice.getText().trim());
            int quantity = Integer.parseInt(txtQuantity.getText().trim());
            int reorderLevel = txtReorderLevel.getText().trim().isEmpty() ? 10 : Integer.parseInt(txtReorderLevel.getText().trim());
            java.sql.Date expiryDate = java.sql.Date.valueOf(txtExpiryDate.getText().trim());

            Integer supplierId = txtSupplierId.getText().trim().isEmpty()
                    ? null
                    : Integer.parseInt(txtSupplierId.getText().trim());

            Medicine newMedicine = new Medicine(0, name, company, type, price, quantity, reorderLevel, expiryDate, supplierId);

            MedicineDAO dao = new MedicineDAO();
            dao.addMedicine(newMedicine);

            javax.swing.JOptionPane.showMessageDialog(this, "Medicine added successfully!");
            clearForm();
            loadMedicinesTable();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Price, Quantity, Reorder Level, and Supplier ID must be numbers.");
        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Expiry date must be in YYYY-MM-DD format.");
        } catch (java.sql.SQLException e) {
            if (e.getMessage().contains("foreign key constraint")) {
                javax.swing.JOptionPane.showMessageDialog(this, "That Supplier ID doesn't exist. Leave it blank or enter a valid supplier ID.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            }
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int row = tblMedicines.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a medicine from the table first.");
            return;
        }

        try {
            int medicineId = (int) tableModel.getValueAt(row, 0);

            String name = txtName.getText().trim();
            String company = txtCompany.getText().trim();
            String type = txtType.getText().trim();
            java.math.BigDecimal price = new java.math.BigDecimal(txtPrice.getText().trim());
            int quantity = Integer.parseInt(txtQuantity.getText().trim());
            int reorderLevel = Integer.parseInt(txtReorderLevel.getText().trim());
            java.sql.Date expiryDate = java.sql.Date.valueOf(txtExpiryDate.getText().trim());
            Integer supplierId = txtSupplierId.getText().trim().isEmpty()
                    ? null
                    : Integer.parseInt(txtSupplierId.getText().trim());

            Medicine updated = new Medicine(medicineId, name, company, type, price, quantity, reorderLevel, expiryDate, supplierId);

            MedicineDAO dao = new MedicineDAO();
            dao.updateMedicine(updated);

            javax.swing.JOptionPane.showMessageDialog(this, "Medicine updated successfully!");
            clearForm();
            loadMedicinesTable();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Price, Quantity, Reorder Level, and Supplier ID must be numbers.");
        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Expiry date must be in YYYY-MM-DD format.");
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tblMedicines.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a medicine from the table first.");
            return;
        }

        int medicineId = (int) tableModel.getValueAt(row, 0);
        String name = tableModel.getValueAt(row, 1).toString();

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Delete \"" + name + "\"? This cannot be undone.",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            try {
                MedicineDAO dao = new MedicineDAO();
                dao.deleteMedicine(medicineId);
                javax.swing.JOptionPane.showMessageDialog(this, "Medicine deleted.");
                clearForm();
                loadMedicinesTable();
            } catch (java.sql.SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

