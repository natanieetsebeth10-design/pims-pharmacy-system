    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txtSupplierId.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a supplier from the table first.");
            return;
        }
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                "Delete this supplier? Medicines linked to it will have their supplier cleared.",
                "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            SupplierDAO dao = new SupplierDAO();
            if (dao.deleteSupplier(Integer.parseInt(txtSupplierId.getText()))) {
                javax.swing.JOptionPane.showMessageDialog(this, "Supplier deleted.");
                loadSuppliersToTable();
                clearFields();
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
            Supplier s = new Supplier();
            s.setName(txtName.getText());
            s.setContactPerson(txtContactPerson.getText());
            s.setPhone(txtPhone.getText());
            s.setEmail(txtEmail.getText());
            s.setAddress(txtAddress.getText());

            SupplierDAO dao = new SupplierDAO();
            if (dao.addSupplier(s)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Supplier added successfully.");
                loadSuppliersToTable();
                clearFields();
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txtSupplierId.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a supplier from the table first.");
            return;
        }
        try {
            Supplier s = new Supplier();
            s.setSupplierId(Integer.parseInt(txtSupplierId.getText()));
            s.setName(txtName.getText());
            s.setContactPerson(txtContactPerson.getText());
            s.setPhone(txtPhone.getText());
            s.setEmail(txtEmail.getText());
            s.setAddress(txtAddress.getText());

            SupplierDAO dao = new SupplierDAO();
            if (dao.updateSupplier(s)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Supplier updated successfully.");
                loadSuppliersToTable();
                clearFields();
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

