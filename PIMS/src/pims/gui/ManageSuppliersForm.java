    private void loadSuppliersToTable() {
        try {
            SupplierDAO dao = new SupplierDAO();
            java.util.List<Supplier> suppliers = dao.getAllSuppliers();

            javax.swing.table.DefaultTableModel model
                    = new javax.swing.table.DefaultTableModel(
                            new Object[]{"ID", "Name", "Contact Person", "Phone", "Email", "Address"}, 0);

            for (Supplier s : suppliers) {
                model.addRow(new Object[]{
                    s.getSupplierId(), s.getName(), s.getContactPerson(),
                    s.getPhone(), s.getEmail(), s.getAddress()
                });
            }
            tblSuppliers.setModel(model);

// Customize column widths
            javax.swing.table.TableColumnModel columnModel = tblSuppliers.getColumnModel();
            columnModel.getColumn(0).setPreferredWidth(40);   // ID - narrow
            columnModel.getColumn(1).setPreferredWidth(140);  // Name
            columnModel.getColumn(2).setPreferredWidth(140);  // Contact Person
            columnModel.getColumn(3).setPreferredWidth(100);  // Phone
            columnModel.getColumn(4).setPreferredWidth(160);  // Email
            columnModel.getColumn(5).setPreferredWidth(220);  // Address - widest
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading suppliers: " + e.getMessage());
        }
    }

