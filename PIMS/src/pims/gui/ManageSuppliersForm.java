    private void tblSuppliersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSuppliersMouseClicked
        int row = tblSuppliers.getSelectedRow();
        if (row == -1) {
            return;
        }

        txtSupplierId.setText(tblSuppliers.getValueAt(row, 0).toString());
        txtName.setText(tblSuppliers.getValueAt(row, 1).toString());
        txtContactPerson.setText(tblSuppliers.getValueAt(row, 2).toString());
        txtPhone.setText(tblSuppliers.getValueAt(row, 3).toString());
        txtEmail.setText(tblSuppliers.getValueAt(row, 4).toString());
        txtAddress.setText(tblSuppliers.getValueAt(row, 5).toString());
    }//GEN-LAST:event_tblSuppliersMouseClicked

