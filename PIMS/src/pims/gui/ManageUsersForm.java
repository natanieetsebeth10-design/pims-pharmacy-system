    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txtUserId.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a user from the table first.");
            return;
        }

        try {
            pims.dao.UserDAO dao = new pims.dao.UserDAO();
            long adminCount = dao.getAllUsers().stream().filter(u -> "Admin".equals(u.getRole())).count();
            boolean deletingAnAdmin = "Admin".equals(tblUsers.getValueAt(tblUsers.getSelectedRow(), 3));

            if (deletingAnAdmin && adminCount <= 1) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete the last remaining Admin account.");
                return;
            }

            int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                    "Delete this user account?", "Confirm Delete",
                    javax.swing.JOptionPane.YES_NO_OPTION);
            if (confirm != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }

            if (dao.deleteUser(Integer.parseInt(txtUserId.getText()))) {
                javax.swing.JOptionPane.showMessageDialog(this, "User deleted.");
                loadUsersToTable();
                clearFields();
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txtUsername.getText().isEmpty() || txtPassword.getText().isEmpty() || txtFullName.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }
        try {
            pims.dao.UserDAO dao = new pims.dao.UserDAO();

            if (dao.usernameExists(txtUsername.getText())) {
                javax.swing.JOptionPane.showMessageDialog(this, "That username is already taken.");
                return;
            }

            pims.model.User u = new pims.model.User(
                    0,
                    txtUsername.getText(),
                    txtPassword.getText(),
                    (String) cmbRole.getSelectedItem(),
                    txtFullName.getText()
            );

            if (dao.addUser(u)) {
                javax.swing.JOptionPane.showMessageDialog(this, "User added successfully.");
                loadUsersToTable();
                clearFields();
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnAddActionPerformed

