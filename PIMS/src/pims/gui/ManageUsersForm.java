    private void loadUsersToTable() {
        try {
            pims.dao.UserDAO dao = new pims.dao.UserDAO();
            java.util.List<pims.model.User> users = dao.getAllUsers();

            javax.swing.table.DefaultTableModel model
                    = new javax.swing.table.DefaultTableModel(
                            new Object[]{"ID", "Username", "Password", "Role", "Full Name"}, 0);

            for (pims.model.User u : users) {
                model.addRow(new Object[]{
                    u.getUserId(), u.getUsername(), u.getPassword(), u.getRole(), u.getFullName()
                });
            }
            tblUsers.setModel(model);

            javax.swing.table.TableColumnModel columnModel = tblUsers.getColumnModel();
            columnModel.getColumn(0).setPreferredWidth(40);
            columnModel.getColumn(1).setPreferredWidth(120);
            columnModel.getColumn(2).setPreferredWidth(100);
            columnModel.getColumn(3).setPreferredWidth(80);
            columnModel.getColumn(4).setPreferredWidth(160);

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading users: " + e.getMessage());
        }
    }

